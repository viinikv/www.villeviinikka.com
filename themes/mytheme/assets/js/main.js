function toggleDarkMode(init=false){
  const names = ["light dark", "light", "dark"];
  if (init) {
    idx = 0;
  }
  try {
    const theme = localStorage.getItem("theme");
    if (theme) {
      idx = names.indexOf(theme);
      idx = Math.max(idx, 0);
    }
  } catch {}

  if (!init) {
    idx = (idx + 1) % names.length;
  }
  const newtheme = names[idx];
  if (!init) {
    try {
      localStorage.setItem("theme", newtheme);
    } catch {}
  }
  document.documentElement.setAttribute("data-theme", newtheme);
  console.log("Setting theme to: " + newtheme + ", init="+init);
  document.documentElement.setAttribute("style", "color-scheme: "+newtheme+";");
};

